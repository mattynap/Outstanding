/** Unisce i pixel orizzontali uguali in un solo rettangolo: meno nodi SVG. */
export function pxRuns(rows: readonly string[]): PxRun[] {
  const runs: PxRun[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c === '.') {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === c) w++;
      runs.push({ x, y, w, c: c as PxCell });
      x += w;
    }
  });
  return runs;
}
